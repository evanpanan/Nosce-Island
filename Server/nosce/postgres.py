"""PostgreSQL persistence for Vercel. SQL here adapts the existing, bounded SQLite query set.
No local database or process-global connection is used in serverless deployments.
"""
from contextvars import ContextVar
from contextlib import contextmanager
import re
import sqlite3
import time
import psycopg
from psycopg.rows import dict_row


class Row(dict):
    def __getitem__(self,key):
        return list(self.values())[key] if isinstance(key,int) else super().__getitem__(key)


class Result:
    def __init__(self,rows): self.rows=rows
    def fetchone(self): return self.rows[0] if self.rows else None
    def fetchall(self): return self.rows
    def __iter__(self): return iter(self.rows)


def translate(query):
    query=query.strip().rstrip(";")
    query=re.sub(r"\bINSERT OR IGNORE INTO\b","INSERT INTO",query,flags=re.I) + (" ON CONFLICT DO NOTHING" if re.search(r"\bINSERT OR IGNORE\b",query,re.I) else "")
    if re.search(r"INSERT OR REPLACE INTO reconciliations",query,re.I):
        query=re.sub("INSERT OR REPLACE","INSERT",query,flags=re.I)+" ON CONFLICT(original_id) DO UPDATE SET checked=excluded.checked"
    elif re.search(r"INSERT OR REPLACE INTO limits",query,re.I):
        query=re.sub("INSERT OR REPLACE","INSERT",query,flags=re.I)+" ON CONFLICT(key) DO UPDATE SET bucket=excluded.bucket,count=excluded.count,updated=excluded.updated"
    query=query.replace("max(created,last_seen)","greatest(created,last_seen)")
    # Preserve JSON API camel-case aliases under PostgreSQL's case-folding rules.
    query=re.sub(r"\bAS ([a-zA-Z_][a-zA-Z_0-9]*)",lambda m:'AS "'+m[1]+'"' if any(c.isupper() for c in m[1]) and any(c.islower() for c in m[1]) else m[0],query)
    return query.replace("%","%%").replace("?","%s")


class PostgresDB:
    def __init__(self,url):
        self.url=url
        self.current=ContextVar("nosce_postgres_"+str(id(self)),default=None)

    @contextmanager
    def session(self):
        if self.current.get() is not None:
            yield self.current.get();return
        connection=None
        for attempt in range(3):
            try:
                connection=psycopg.connect(self.url,autocommit=True,row_factory=dict_row,connect_timeout=5)
                break
            except psycopg.OperationalError:
                if attempt==2:raise
                time.sleep(0.05*(attempt+1))
        with connection:
            token=self.current.set(connection)
            try: yield connection
            finally:self.current.reset(token)

    @contextmanager
    def atomic(self):
        with self.session() as connection:
            with connection.transaction():
                # Bound synchronous critical sections only, never hold this across provider network calls.
                connection.execute("SELECT pg_advisory_xact_lock(1948736201)")
                yield

    def execute(self,query,params=()):
        try:
            with self.session() as connection:
                cursor=connection.execute(translate(query),params)
                return Result([Row(row) for row in cursor.fetchall()] if cursor.description else [])
        except psycopg.IntegrityError as error:
            raise sqlite3.IntegrityError("Database constraint violation") from error

    def initialize(self,schema):
        with self.atomic():
            self.execute("CREATE TABLE IF NOT EXISTS schema_version(version INTEGER PRIMARY KEY)")
            if self.execute("SELECT version FROM schema_version WHERE version=1").fetchone():return
            for statement in schema.split(";"):
                statement=statement.strip()
                if not statement or statement.startswith("PRAGMA"):continue
                statement=re.sub(r"\bBLOB\b","BYTEA",statement)
                statement=re.sub(r"\bREAL\b","DOUBLE PRECISION",statement)
                statement=statement.replace("audit(id INTEGER PRIMARY KEY","audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
                self.execute(statement)
            self.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS app_store_hash TEXT")
            self.execute("CREATE UNIQUE INDEX IF NOT EXISTS app_store_identity ON users(app_store_hash)")
            self.execute("ALTER TABLE installs ADD COLUMN IF NOT EXISTS user_id TEXT")
            self.execute("ALTER TABLE installs ADD COLUMN IF NOT EXISTS last_seen DOUBLE PRECISION NOT NULL DEFAULT 0")
            self.execute("CREATE TABLE IF NOT EXISTS runtime_cache(key TEXT PRIMARY KEY,payload TEXT NOT NULL,updated DOUBLE PRECISION NOT NULL)")
            self.execute("INSERT INTO schema_version VALUES(1)")

    def close(self): pass
